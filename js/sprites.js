// Scaled crisp icon as a data URL for DOM cards.
function iconURL(name, scale = 4) {
  const key = name + '@' + scale;
  if (Assets.iconURL[key]) return Assets.iconURL[key];
  const src = Assets.icons[name] || Assets.icons.skullIcon;
  const c = makeCanvas(src.width * scale, src.height * scale);
  const g = c.getContext('2d');
  g.imageSmoothingEnabled = false;
  g.drawImage(src, 0, 0, c.width, c.height);
  return (Assets.iconURL[key] = c.toDataURL());
}

function spriteURL(name, scale = 4) {
  const key = 'spr:' + name + '@' + scale;
  if (Assets.iconURL[key]) return Assets.iconURL[key];
  const src = Assets.sprites[name].frames[0];
  const c = makeCanvas(src.width * scale, src.height * scale);
  const g = c.getContext('2d');
  g.imageSmoothingEnabled = false;
  g.drawImage(src, 0, 0, c.width, c.height);
  return (Assets.iconURL[key] = c.toDataURL());
}
